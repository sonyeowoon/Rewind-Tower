// Hand-authored rooms and orthogonal corridors; no randomized or mirrored level generation.
// Coordinates are [row, column]. V is an impassable void between suspended islands.
function makeMap(width, height, rooms, corridors, objects, suspended = false) {
  const map = Array.from({ length: height }, (_, r) => Array.from({ length: width }, (_, c) =>
    suspended && r > 0 && c > 0 && r < height - 1 && c < width - 1 ? 'V' : '#'));
  const put = (r, c, tile = '.') => {
    if (r <= 0 || c <= 0 || r >= height - 1 || c >= width - 1) throw new Error('Map feature outside its border');
    map[r][c] = tile;
  };
  for (const [top, left, bottom, right] of rooms)
    for (let r = top; r <= bottom; r++) for (let c = left; c <= right; c++) put(r, c);
  for (const points of corridors) for (let i = 1; i < points.length; i++) {
    let [r, c] = points[i - 1]; const [endR, endC] = points[i];
    if (r !== endR && c !== endC) throw new Error('Corridors must be orthogonal');
    const dr = Math.sign(endR - r), dc = Math.sign(endC - c);
    put(r, c);
    while (r !== endR || c !== endC) { r += dr; c += dc; put(r, c); }
  }
  for (const [tile, r, c] of objects) {
    if (map[r]?.[c] !== '.') throw new Error(`Object ${tile} needs a floor at ${r},${c}`);
    put(r, c, tile);
  }
  return map;
}

